-- ============================================================
--  KKS Shopping Store — Database (v3)
--  Storefront + customer accounts + orders + inventory + back office
--  MySQL 5.7+ / MariaDB 10.3+   (InnoDB, utf8mb4)
--  Import once.  Then create your first admin with:
--      php tools/create_admin.php
-- ============================================================
CREATE DATABASE IF NOT EXISTS kksshopping CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE kksshopping;
SET NAMES utf8mb4;

-- ── Catalogue ─────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS products (
  id                  INT AUTO_INCREMENT PRIMARY KEY,
  model               VARCHAR(100) NOT NULL UNIQUE,
  name                VARCHAR(255) NOT NULL,
  category            VARCHAR(100) NOT NULL,
  subcategory         VARCHAR(100) NOT NULL,
  icon_slug           VARCHAR(50)  NOT NULL DEFAULT 'default',
  image_url           VARCHAR(500) DEFAULT NULL,
  pcs_per_box         INT          DEFAULT NULL,
  description         TEXT         DEFAULT NULL,
  stock_qty           INT          DEFAULT NULL COMMENT 'NULL = stock not tracked (always available)',
  low_stock_threshold INT          NOT NULL DEFAULT 5,
  is_featured         TINYINT(1)   NOT NULL DEFAULT 0,
  is_active           TINYINT(1)   NOT NULL DEFAULT 1,
  created_at          TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at          TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_category (category), INDEX idx_subcategory (subcategory), INDEX idx_active (is_active)
) ENGINE=InnoDB;

-- ── Customers (public registration) ───────────────────────
CREATE TABLE IF NOT EXISTS customers (
  id            INT AUTO_INCREMENT PRIMARY KEY,
  name          VARCHAR(120) NOT NULL,
  email         VARCHAR(190) NOT NULL UNIQUE,
  phone         VARCHAR(30)  NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  address       VARCHAR(255) DEFAULT NULL,
  city          VARCHAR(100) DEFAULT NULL,
  is_active     TINYINT(1)   NOT NULL DEFAULT 1,
  created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  last_login_at TIMESTAMP    NULL DEFAULT NULL
) ENGINE=InnoDB;

-- ── Staff accounts (NO public registration; created by CLI/owner) ──
CREATE TABLE IF NOT EXISTS admins (
  id            INT AUTO_INCREMENT PRIMARY KEY,
  username      VARCHAR(60)  NOT NULL UNIQUE,
  name          VARCHAR(120) NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  role          ENUM('owner','staff') NOT NULL DEFAULT 'staff',
  is_active     TINYINT(1)   NOT NULL DEFAULT 1,
  created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  last_login_at TIMESTAMP    NULL DEFAULT NULL
) ENGINE=InnoDB;

-- ── Orders ────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS orders (
  id             INT AUTO_INCREMENT PRIMARY KEY,
  order_no       VARCHAR(30) DEFAULT NULL UNIQUE,
  customer_id    INT NULL,
  status         ENUM('pending','confirmed','packed','dispatched','delivered','cancelled') NOT NULL DEFAULT 'pending',
  payment_status ENUM('unpaid','partial','paid') NOT NULL DEFAULT 'unpaid',
  ship_name      VARCHAR(120) NOT NULL,
  ship_phone     VARCHAR(30)  NOT NULL,
  ship_address   VARCHAR(255) NOT NULL,
  ship_city      VARCHAR(100) NOT NULL,
  notes          VARCHAR(1000) DEFAULT NULL COMMENT 'customer note',
  admin_notes    VARCHAR(2000) DEFAULT NULL COMMENT 'internal only',
  subtotal       DECIMAL(12,2) NOT NULL DEFAULT 0,
  stock_deducted TINYINT(1) NOT NULL DEFAULT 0,
  created_at     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_status (status), INDEX idx_customer (customer_id), INDEX idx_created (created_at),
  CONSTRAINT fk_orders_customer FOREIGN KEY (customer_id) REFERENCES customers(id) ON DELETE SET NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS order_items (
  id         INT AUTO_INCREMENT PRIMARY KEY,
  order_id   INT NOT NULL,
  product_id INT NULL,
  model      VARCHAR(100) NOT NULL,
  name       VARCHAR(255) NOT NULL,
  qty        INT NOT NULL,
  unit_price DECIMAL(12,2) DEFAULT NULL COMMENT 'set by admin when quoting',
  INDEX idx_order (order_id),
  CONSTRAINT fk_items_order   FOREIGN KEY (order_id)   REFERENCES orders(id)   ON DELETE CASCADE,
  CONSTRAINT fk_items_product FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE SET NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS order_events (
  id         INT AUTO_INCREMENT PRIMARY KEY,
  order_id   INT NOT NULL,
  status     VARCHAR(20) NOT NULL,
  note       VARCHAR(500) DEFAULT NULL,
  actor      VARCHAR(80) DEFAULT NULL COMMENT 'customer / admin username',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_order (order_id),
  CONSTRAINT fk_events_order FOREIGN KEY (order_id) REFERENCES orders(id) ON DELETE CASCADE
) ENGINE=InnoDB;

-- ── Inventory audit trail ─────────────────────────────────
CREATE TABLE IF NOT EXISTS stock_movements (
  id         INT AUTO_INCREMENT PRIMARY KEY,
  product_id INT NOT NULL,
  change_qty INT NOT NULL,
  qty_after  INT NOT NULL,
  reason     ENUM('restock','adjustment','order','cancel','initial') NOT NULL,
  ref        VARCHAR(60) DEFAULT NULL,
  note       VARCHAR(255) DEFAULT NULL,
  actor      VARCHAR(80) DEFAULT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_product (product_id, created_at),
  CONSTRAINT fk_mov_product FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE CASCADE
) ENGINE=InnoDB;

-- ── Guest WhatsApp inquiries (kept from v2) ───────────────
CREATE TABLE IF NOT EXISTS inquiries (
  id            INT AUTO_INCREMENT PRIMARY KEY,
  contact_name  VARCHAR(150) DEFAULT NULL,
  contact_phone VARCHAR(50)  DEFAULT NULL,
  items_json    TEXT NOT NULL,
  item_count    INT NOT NULL DEFAULT 0,
  status        ENUM('new','contacted','closed') NOT NULL DEFAULT 'new',
  created_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

-- ── Brute-force protection ────────────────────────────────
CREATE TABLE IF NOT EXISTS login_attempts (
  id         INT AUTO_INCREMENT PRIMARY KEY,
  scope      VARCHAR(16)  NOT NULL,
  ident      VARCHAR(190) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_lookup (scope, ident, created_at)
) ENGINE=InnoDB;

-- ── Store settings ────────────────────────────────────────
CREATE TABLE IF NOT EXISTS settings (
  setting_key   VARCHAR(80) PRIMARY KEY,
  setting_value TEXT
) ENGINE=InnoDB;
